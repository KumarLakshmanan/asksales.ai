import { index, integer, jsonb, numeric, pgTable, serial, timestamp, uniqueIndex, varchar } from 'drizzle-orm/pg-core';
import { businessProfileColumn } from '../businessProfileColumn.js';
import type { InsightsPricingSnapshot } from '../../../shared/insightsBilling.js';

export const aiUsageEventsTable = pgTable('ai_usage_events', {
  id: serial('id').primaryKey(),
  businessProfileId: businessProfileColumn(),
  userId: integer('user_id').notNull(),
  actorUserId: integer('actor_user_id').notNull(),
  organizationId: integer('organization_id'),
  sourceTable: varchar('source_table', { length: 80 }).notNull(),
  sourceId: varchar('source_id', { length: 120 }).notNull(),
  attemptId: varchar('attempt_id', { length: 160 }).notNull(),
  operationId: varchar('operation_id', { length: 160 }).notNull(),
  kind: varchar('kind', { length: 30 }).notNull(),
  process: varchar('process', { length: 100 }).notNull(),
  provider: varchar('provider', { length: 50 }),
  model: varchar('model', { length: 150 }),
  channel: varchar('channel', { length: 30 }).notNull(),
  conversationKind: varchar('conversation_kind', { length: 30 }),
  conversationId: integer('conversation_id'),
  contactId: integer('contact_id'),
  agent: varchar('agent', { length: 150 }),
  inputTokens: integer('input_tokens'),
  outputTokens: integer('output_tokens'),
  totalTokens: integer('total_tokens'),
  cachedTokens: integer('cached_tokens'),
  reasoningTokens: integer('reasoning_tokens'),
  units: numeric('units', { precision: 20, scale: 6 }).notNull().default('1'),
  unit: varchar('unit', { length: 30 }).notNull().default('request'),
  status: varchar('status', { length: 30 }).notNull(),
  durationMs: integer('duration_ms'),
  providerCostUsd: numeric('provider_cost_usd', { precision: 20, scale: 10 }),
  pricingSnapshot: jsonb('pricing_snapshot').$type<InsightsPricingSnapshot>(),
  billingTransactionId: integer('billing_transaction_id'),
  startedAt: timestamp('started_at', { withTimezone: true }).notNull(),
  completedAt: timestamp('completed_at', { withTimezone: true }),
  occurredAt: timestamp('occurred_at', { withTimezone: true }).notNull(),
}, (table) => ({
  sourceUnique: uniqueIndex('ai_usage_events_source_uq').on(table.businessProfileId, table.sourceTable, table.sourceId),
  attemptUnique: uniqueIndex('ai_usage_events_attempt_uq').on(table.businessProfileId, table.attemptId),
  periodIndex: index('ai_usage_events_period_idx').on(table.businessProfileId, table.occurredAt),
  conversationIndex: index('ai_usage_events_conversation_idx').on(table.businessProfileId, table.conversationKind, table.conversationId),
}));
