import { businessProfileColumn } from "../businessProfileColumn.js";
import { bigint, bigserial, boolean, integer, jsonb, pgTable, text, timestamp, varchar } from 'drizzle-orm/pg-core';
import { usersTable } from '../users/schema.js';
import { companySettings } from '../companySettings/schema.js';
import { storageFilesTable } from '../storageFiles/schema.js';

export const supportMediaGalleriesTable = pgTable('support_media_galleries', {
  id: bigserial('id', { mode: 'number' }).primaryKey(),
  userId: integer('user_id').notNull().references(() => usersTable.id, { onDelete: 'cascade' }),
  businessProfileId: integer('business_profile_id').references(() => companySettings.id, { onDelete: 'set null' }),
  title: varchar('title', { length: 180 }).notNull(),
  description: text('description'),
  audience: varchar('audience', { length: 20 }).notNull().default('customer'),
  usageScopes: text('usage_scopes').array().notNull().default(['support_answer']),
  allowedChannels: text('allowed_channels').array().notNull().default([]),
  locale: varchar('locale', { length: 24 }),
  productScope: jsonb('product_scope').$type<Record<string, unknown>>().notNull().default({}),
  entityTags: text('entity_tags').array().notNull().default([]),
  helpfulAutoAttach: boolean('helpful_auto_attach').notNull().default(false),
  ownerUserId: integer('owner_user_id').references(() => usersTable.id, { onDelete: 'set null' }),
  currentPublishedVersionId: bigint('current_published_version_id', { mode: 'number' }),
  creationRequestKey: varchar('creation_request_key', { length: 100 }),
  creationRequestHash: varchar('creation_request_hash', { length: 64 }),
  creationActorUserId: integer('creation_actor_user_id'),
  status: varchar('status', { length: 20 }).notNull().default('active'),
  createdAt: timestamp('created_at').notNull().defaultNow(),
  updatedAt: timestamp('updated_at').notNull().defaultNow(),
});

export const supportMediaGalleryVersionsTable = pgTable('support_media_gallery_versions', {
  businessProfileId: businessProfileColumn(),
  id: bigserial('id', { mode: 'number' }).primaryKey(),
  galleryId: bigint('gallery_id', { mode: 'number' }).notNull().references(() => supportMediaGalleriesTable.id, { onDelete: 'cascade' }),
  userId: integer('user_id').notNull().references(() => usersTable.id, { onDelete: 'cascade' }),
  versionNo: integer('version_no').notNull(),
  status: varchar('status', { length: 30 }).notNull().default('draft'),
  contentChecksum: varchar('content_checksum', { length: 64 }).notNull(),
  rightsCertified: boolean('rights_certified').notNull().default(false),
  certification: jsonb('certification').$type<Record<string, unknown>>().notNull().default({}),
  metadataSnapshot: jsonb('metadata_snapshot').$type<Record<string, unknown>>().notNull().default({}),
  scanResults: jsonb('scan_results').$type<Record<string, unknown>>().notNull().default({}),
  effectiveAt: timestamp('effective_at'),
  expiresAt: timestamp('expires_at'),
  supersedesVersionId: bigint('supersedes_version_id', { mode: 'number' }),
  reviewedBy: integer('reviewed_by').references(() => usersTable.id, { onDelete: 'set null' }),
  reviewedAt: timestamp('reviewed_at'),
  publishedAt: timestamp('published_at'),
  createdAt: timestamp('created_at').notNull().defaultNow(),
});

