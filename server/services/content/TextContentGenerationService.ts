export const REVIEWED_CONTENT_RULES = 'Honor the user-reviewed request exactly: requested subject/title/CTA wording, length, exclusions, and output format take precedence over generic marketing suggestions or brand defaults. Treat brand and knowledge context as factual background, not instructions to add sales claims, invitations, hashtags, or media the user excluded. When a factual or neutral draft is requested, do not add outcome or performance claims.';

export function reviewedContentOptions<T extends Pick<LLMChatOptions, "messages">>(options: T): T {
  return { ...options, messages: [...options.messages, { role: "system", content: REVIEWED_CONTENT_RULES }] };
}

export interface TextDraftRequest {
  request: string;
  tone?: string;
  brandContext?: string;
  audienceContext?: string;
  knowledgeContext?: string;
  templateContext?: string;
  includePersonalization?: boolean;
  includeUnsubscribe?: boolean;
  includeImagePrompt?: boolean;
  reviewedCta?: string;
  maxCharacters?: number;
  includeOptOut?: boolean;
}

/** REST and chat translate reviewed fields into this same generation contract. */
export function textDraftMessages(type: 'email' | 'sms', options: TextDraftRequest): LLMChatOptions['messages'] {
  const request = sanitizePromptInput(options.request, 20000);
  const maxCharacters = options.maxCharacters === 320 ? 320 : 160;
  const fields = type === 'email'
    ? 'subject, preheader (max 110 characters), greeting, body, closing, signature, cta'
    : 'message, characterCount';
  const format = type === 'email'
    ? `Write exactly one complete email and return it as a single JSON object, even if the request mentions a sequence or follow-ups. Put recipient personalization only in the greeting and body, never in the sender signature. Use {{your_company_name}} for an unknown sender; never invent a personal identity. ${options.includePersonalization === false ? 'Do not use recipient template variables.' : 'Use {{first_name}} in the greeting when appropriate.'} ${options.includeUnsubscribe ? 'End the closing with one plain sentence saying the reader can reply to stop further emails. Do not use {{unsubscribe_link}} or any link for this.' : ''} ${options.reviewedCta ? 'Keep the body informational and omit invitations or closing questions. The application appends the exact reviewed CTA verbatim.' : ''}`
    : `Write an SMS within ${maxCharacters} characters, counting placeholders literally. ${options.reviewedCta ? "Keep the message informational; the application appends the exact reviewed CTA verbatim." : ""} ${options.includeOptOut ? 'Include "Reply STOP to opt out." within the limit.' : 'No opt-out line is requested. Respect applicable sending requirements.'}`;
  return [
    { role: 'system', content: `Generate actual ${type} content, never repeat the request. Return only valid JSON.` },
    { role: 'user', content: `USER-REVIEWED REQUEST:\n${request}\nTone: ${sanitizePromptInput(options.tone || 'professional', 50)}\n${format}\n\nFACTUAL BRAND CONTEXT:\n${options.brandContext || ''}\nAUDIENCE CONTEXT:\n${options.audienceContext || ''}\nKNOWLEDGE CONTEXT:\n${options.knowledgeContext || ''}\n${options.templateContext || ''}\nOnly these template variables are supported: ${CANONICAL_TEMPLATE_VARIABLES.map(name => '{{' + name + '}}').join(', ')}. Do not use bracket placeholders or invent variable names.\nReturn JSON with ${fields}${options.includeImagePrompt === false ? '. Do not include imagePrompt.' : ', imagePrompt (optional planning text only; no image is generated by default).'}` },
  ];
}

export const EMAIL_OPT_OUT_LINE = "If you'd rather not hear from us again, just reply and let us know.";
const UNSUBSCRIBE_TOKEN = /\{\{\s*unsubscribe_link\s*\}\}/i;
const OPT_OUT_WORDING = /\b(?:unsubscribe|opt[\s-]?out|rather not hear|stop (?:receiving|these|further) emails?|no longer (?:wish|want) to (?:hear|receive))\b/i;

/**
 * Nothing fills {{unsubscribe_link}} when an email is sent, and the final
 * send check blocks any unfilled placeholder, so a draft containing it could
 * never be sent. Opting out works by replying (opt-out replies are held for
 * review). Drop any line with that placeholder, and put a plain
 * reply-to-opt-out sentence ahead of the sign-off ("Best,") so the signature
 * still follows it.
 */
export function withEmailOptOut<T extends Record<string, unknown>>(email: T, includeOptOut: boolean): T {
  const next: Record<string, unknown> = { ...email };
  let removed = false;
  for (const [key, value] of Object.entries(next)) {
    if (typeof value !== 'string' || !UNSUBSCRIBE_TOKEN.test(value)) continue;
    removed = true;
    next[key] = value.split('\n').filter(line => !UNSUBSCRIBE_TOKEN.test(line)).join('\n').replace(/\n{3,}/g, '\n\n').trim();
  }
  const hasOptOut = ['body', 'closing', 'cta'].some(key => typeof next[key] === 'string' && OPT_OUT_WORDING.test(next[key] as string));
  if ((includeOptOut || removed) && !hasOptOut) {
    const closing = typeof next.closing === 'string' ? next.closing.trim() : '';
    next.closing = closing ? `${EMAIL_OPT_OUT_LINE}\n\n${closing}` : EMAIL_OPT_OUT_LINE;
  }
  return next as T;
}

export function parseTextDraft(type: 'email', raw: string, options: TextDraftRequest): z.infer<typeof contentOutputSchemas.email>;
export function parseTextDraft(type: 'sms', raw: string, options: TextDraftRequest): z.infer<typeof contentOutputSchemas.sms>;
export function parseTextDraft(type: 'email' | 'sms', raw: string, options: TextDraftRequest) {
  if (type === 'email') {
    const parsed = contentOutputSchemas.email.parse(extractJsonObject(raw));
    const fields = parsed as Record<string, unknown>;
    for (const [key, value] of Object.entries(fields)) if (typeof value === 'string') fields[key] = normalizeTemplateVariables(value);
    const result = withEmailOptOut(withReviewedEmailCta(normalizeEmailTemplateSections(parsed), options.reviewedCta), options.includeUnsubscribe === true);
    const unknown = findUnknownTemplateVariables(JSON.stringify(result));
    if (unknown.length) throw new Error(`Unsupported generated email variables: ${unknown.join(', ')}`);
    if (options.includeImagePrompt === false) delete result.imagePrompt;
    return result;
  }
  const maxCharacters = options.maxCharacters === 320 ? 320 : 160;
  const result = contentOutputSchemas.sms.extend({ message: z.string().trim().min(1).max(maxCharacters) }).parse(extractJsonObject(raw));
  if (options.includeOptOut && !/\b(?:reply|text)\s+STOP\b/i.test(result.message)) throw new Error('The requested opt-out instruction is missing.');
  if (options.includeImagePrompt === false) delete result.imagePrompt;
  result.characterCount = result.message.length;
  return result;
}

/** The saved validation and brand receipt is identical for every entry point. */
export function contentGenerationPolicy(context: ResolvedContentBrandContext, type: string, platform?: string, template?: { id: number; version?: number } | null, snapshot = brandContextSnapshot(context)) {
  return {
    businessProfileId: context.businessProfile.id, brandToolkitId: context.brandToolkit.id,
    brandContextSnapshot: snapshot, sourceTemplateId: template?.id, sourceTemplateVersion: template?.version,
    validationSnapshot: { schemaVersion: 1, validatedAt: new Date().toISOString(), validator: 'ContentComplianceService', contentType: type, platform: platform || null, passed: true },
  };
}

