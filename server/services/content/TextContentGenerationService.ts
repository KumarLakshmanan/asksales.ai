export async function persistTextDraft(options: {
  type: 'email' | 'sms'; output: Record<string, unknown>; userId: number; threadId?: number | null;
  context: ResolvedContentBrandContext; title?: string; template?: { id: number; version?: number } | null;
  performance?: Record<string, unknown> | null; imageUrl?: string | null;
}) {
  validateGeneratedContent({ type: options.type, output: options.output, context: options.context, platform: options.type, ...(options.type === 'sms' ? { smsMaxCharacters: Number(options.performance?.maxCharacters) || 160 } : {}) });
  const { ContentAssetModel } = await import('../../models/contentAssets/functions.js');
  const asset = await ContentAssetModel.create({
    type: options.type === 'email' ? 'email_template' : 'sms_template',
    title: options.title || (options.type === 'email' ? String(options.output.subject || 'Email Template') : 'SMS Message'),
    content: options.type === 'email' ? JSON.stringify(options.output) : String(options.output.message),
    channel: options.type, status: 'draft', userId: options.userId, threadId: options.threadId || null,
    performance: options.performance || null, ...(options.imageUrl ? { imageUrl: options.imageUrl } : {}),
    ...contentGenerationPolicy(options.context, options.type, options.type, options.template),
  });
  if (asset?.id) {
    const { webSocketEmitter } = await import("../agents/WebSocketEmitter.js");
    webSocketEmitter.emit(options.userId, "content_asset_updated", { assetId: asset.id, type: asset.type, threadId: options.threadId || null });
  }
  return asset;
}

const SIGN_OFF_LINE = /^(?:best|best regards|regards|kind regards|warm regards|warmly|thanks|thank you|many thanks|cheers|sincerely|yours sincerely|all the best)[,.!]?$/i;

/**
 * A reviewed outreach email is sent exactly as saved; nothing appends a
 * signature or unsubscribe link later. Keep every draft consistent: no
 * unfilled {{unsubscribe_link}}, the reply-to-opt-out sentence ahead of the
 * sign-off, and a sign-off that names the sender when the business is known.
 */
export function normalizeOutreachEmailBody(body: string, senderName?: string | null): string {
  const lines = body.replace(/\r\n/g, '\n').split('\n').filter(line => !UNSUBSCRIBE_TOKEN.test(line));
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  const name = senderName?.trim();
  let signOff = -1;
  for (let i = lines.length - 1; i >= Math.max(0, lines.length - 4); i--) {
    if (SIGN_OFF_LINE.test(lines[i].trim())) { signOff = i; break; }
  }
  if (signOff === -1 && name) {
    lines.push('', 'Best,', name);
    signOff = lines.length - 2;
  } else if (signOff !== -1 && name && lines.slice(signOff + 1).every(line => !line.trim())) {
    lines.splice(signOff + 1, lines.length, name);
  }
  if (!OPT_OUT_WORDING.test(lines.join('\n'))) {
    if (signOff === -1) lines.push('', EMAIL_OPT_OUT_LINE);
    else lines.splice(signOff, 0, EMAIL_OPT_OUT_LINE, '');
  }
  return lines.join('\n').replace(/\n{3,}/g, '\n\n').trim();
}
