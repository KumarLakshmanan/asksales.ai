import { describe, expect, it } from "@jest/globals";
import { PgDialect } from "drizzle-orm/pg-core";
import type { SQL } from "drizzle-orm";
import {
  AdminProposalTemplateService,
  type AdminTemplateInput,
} from "../services/AdminProposalTemplateService.js";
import { proposalTemplatesTable } from "../models/proposalTemplates/schema.js";

type Template = typeof proposalTemplatesTable.$inferSelect;
type Audit = {
  id: number;
  templateId: number;
  adminId: number | null;
  action: string;
  snapshot: Template;
};
const dialect = new PgDialect();
function template(id: number, overrides: Partial<Template> = {}): Template {
  return {
    id,
    userId: null,
    businessProfileId: null,
    name: `Template ${id}`,
    category: "Consulting",
    description: "",
    published: true,
    version: 1,
    templateType: "document",
    templateKey: null,
    isDefault: false,
    coverNote: null,
    lineItems: [],
    termsAndConditions: null,
    includeKnowledgeBase: true,
    includeBusinessProfile: true,
    sourceFileName: null,
    sourceMimeType: null,
    sourceText: null,
    sourceHtml: null,
    createdAt: new Date("2026-09-01"),
    updatedAt: new Date("2026-09-01"),
    templateContent: {
      sections: [
        {
          title: "Scope",
          body: "Deliver the agreed discovery workshop.",
          kind: "content",
        },
      ],
      placeholders: [],
      requiredFields: [],
      warnings: [],
    },
    ...overrides,
  };
}
function fixture(
  initial: Template[],
  initialAudit: Audit[] = [],
  failAudit?: string,
) {
  let rows = new Map(initial.map((row) => [row.id, row])),
    audits = [...initialAudit];
  const queries: { sql: string; params: unknown[] }[] = [];
  const visible = (condition: SQL) => {
    const query = dialect.sqlToQuery(condition);
    queries.push(query);
    const row = rows.get(Number(query.params[0]));
    // Exercise the actual predicate generated by the service, including the global-template guard.
    return row && query.sql.includes('"user_id" is null') && row.userId === null
      ? row
      : undefined;
  };
  const database = {
    transaction: async <T>(work: (tx: unknown) => Promise<T>) => {
      const beforeRows = new Map(rows),
        beforeAudit = [...audits];
      try {
        return await work(database);
      } catch (error) {
        rows = beforeRows;
        audits = beforeAudit;
        throw error;
      }
    },
    select: () => ({
      from: () => ({
        where: (condition: SQL) => ({
          limit: async () => {
            const row = visible(condition);
            return row ? [row] : [];
          },
        }),
      }),
    }),
    update: () => ({
      set: (data: Partial<Template>) => ({
        where: (condition: SQL) => ({
          returning: async () => {
            const row = visible(condition);
            if (!row) return [];
            const next = { ...row, ...data };
            rows.set(row.id, next);
            return [next];
          },
        }),
      }),
    }),
    insert: () => ({
      values: (data: Partial<Template>) => ({
        returning: async () => {
          const next = template(Math.max(...rows.keys(), 0) + 1, data);
          rows.set(next.id, next);
          return [next];
        },
      }),
    }),
    execute: async (value: SQL) => {
      const query = dialect.sqlToQuery(value);
      queries.push(query);
      if (query.sql.includes("count(*)"))
        return {
          rows: [
            {
              n: [...rows.values()].filter(
                (row) =>
                  row.userId === null &&
                  row.published &&
                  row.id !== query.params[0],
              ).length,
            },
          ],
        };
      if (query.sql.startsWith("SELECT snapshot"))
        return {
          rows: audits
            .filter(
              (row) =>
                row.id === query.params[0] &&
                row.templateId === query.params[1],
            )
            .map((row) => ({ snapshot: row.snapshot })),
        };
      if (query.sql.startsWith("INSERT INTO proposal_template_audit")) {
        const baseline = query.sql.includes("version_baseline"),
          action = baseline ? "version_baseline" : String(query.params[2]);
        if (action === failAudit) throw new Error("Audit write failed");
        const snapshot = JSON.parse(
          query.params[baseline ? 1 : 3] as string,
        ) as Template;
        if (
          !baseline ||
          !audits.some(
            (audit) =>
              audit.templateId === snapshot.id &&
              audit.snapshot.version === snapshot.version,
          )
        )
          audits.push({
            id: Math.max(...audits.map((audit) => audit.id), 0) + 1,
            templateId: snapshot.id,
            adminId: baseline ? null : Number(query.params[1]),
            action,
            snapshot,
          });
      }
      return { rows: [] };
    },
  };
  return {
    service: new AdminProposalTemplateService(database),
    rows: () => [...rows.values()],
    audits: () => audits,
    queries,
  };
}
const input = (
  overrides: Partial<AdminTemplateInput> = {},
): AdminTemplateInput => ({
  name: "New standard",
  category: "Consulting",
  published: true,
  templateContent: template(1).templateContent!,
  ...overrides,
});
const fullLibrary = () =>
  Array.from({ length: 10 }, (_, index) => template(index + 1));

describe("admin proposal template publishing and rollback", () => {
  it("rejects an eleventh publication before changing any template", async () => {
    const state = fixture(fullLibrary());
    await expect(state.service.save(input(), 9)).rejects.toMatchObject({
      status: 409,
    });
    expect(state.rows().filter((row) => row.published)).toHaveLength(10);
    expect(state.audits()).toHaveLength(0);
    expect(state.queries[0].sql).toContain("pg_advisory_xact_lock");
  });
  it("replaces one slot, preserves the old version and audits both changes", async () => {
    const state = fixture(fullLibrary());
    const saved = await state.service.save(input({ replaceTemplateId: 3 }), 9);
    expect(saved).toMatchObject({
      name: "New standard",
      published: true,
      category: "Consulting",
    });
    expect(state.rows().filter((row) => row.published)).toHaveLength(10);
    expect(state.rows().find((row) => row.id === 3)).toMatchObject({
      published: false,
      version: 2,
    });
    expect(state.audits().map((row) => row.action)).toEqual([
      "version_baseline",
      "replaced",
      "created",
    ]);
    expect(state.audits()[0].snapshot).toMatchObject({
      published: true,
      version: 1,
    });
    expect(
      state
        .audits()
        .slice(1)
        .every((row) => row.adminId === 9),
    ).toBe(true);
  });
  it("rolls back the entire slot replacement if its audit cannot commit", async () => {
    const state = fixture(fullLibrary(), [], "created");
    await expect(
      state.service.save(input({ replaceTemplateId: 3 }), 9),
    ).rejects.toThrow("Audit write failed");
    expect(state.rows()).toHaveLength(10);
    expect(state.rows().find((row) => row.id === 3)).toMatchObject({
      published: true,
      version: 1,
    });
    expect(state.audits()).toHaveLength(0);
  });
  it("blocks private-template replacement and stale editor versions", async () => {
    const state = fixture([
      ...fullLibrary(),
      template(11, { userId: 42 }),
      template(12, { published: false, version: 4 }),
    ]);
    await expect(
      state.service.save(input({ replaceTemplateId: 11 }), 9),
    ).rejects.toMatchObject({ status: 404 });
    await expect(
      state.service.save(
        input({ published: false, expectedVersion: 3 }),
        9,
        12,
      ),
    ).rejects.toMatchObject({ status: 409 });
    expect(state.audits()).toHaveLength(0);
  });
  it("uses the same ten-slot rules when restoring a published version", async () => {
    const current = template(11, { published: false, version: 5 });
    const history = [
      {
        id: 8,
        templateId: 11,
        adminId: 9,
        action: "updated",
        snapshot: template(11, { name: "Original scope", version: 2 }),
      },
    ];
    const state = fixture([...fullLibrary(), current], history);
    await expect(state.service.rollback(11, 8, 9, 5)).rejects.toMatchObject({
      status: 409,
    });
    const restored = await state.service.rollback(11, 8, 9, 5, 4);
    expect(restored).toMatchObject({
      name: "Original scope",
      published: true,
      version: 6,
    });
    expect(state.rows().filter((row) => row.published)).toHaveLength(10);
    expect(state.audits().at(-1)).toMatchObject({
      action: "rolled_back_to_v2",
      adminId: 9,
    });
  });
  it("does not restore a snapshot from another template or a tenant template", async () => {
    const state = fixture(
      [template(1), template(2, { userId: 42 })],
      [
        {
          id: 8,
          templateId: 2,
          adminId: 9,
          action: "updated",
          snapshot: template(2),
        },
      ],
    );
    await expect(state.service.rollback(1, 8, 9, 1)).rejects.toMatchObject({
      status: 404,
    });
    await expect(state.service.rollback(2, 8, 9, 1)).rejects.toMatchObject({
      status: 404,
    });
    expect(state.audits()).toHaveLength(1);
  });
});
