import { StrictMode } from "react";
import { act, cleanup, renderHook } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import api from "@/lib/api";
import { selectBusinessProfile } from "@/lib/business-profile";
import { gmailAuthorizationUrl, gmailCallbackErrorMessage } from "@/lib/gmail-oauth";
import { GMAIL_AUTHORIZATION_TIMEOUT_MS, useGmailAuthorization } from "@/app/dashboard/(main)/integrations/email/useGmailAuthorization";

vi.mock("@/lib/api", () => ({ default: { get: vi.fn() } }));
const get = vi.mocked(api.get);
const authUrl = "https://accounts.google.com/o/oauth2/v2/auth?client_id=fixture&state=fixture-state";
function deferred<T>() {
  let resolve!: (value: T) => void;
  let reject!: (reason: unknown) => void;
  const promise = new Promise<T>((yes, no) => { resolve = yes; reject = no; });
  return { promise, resolve, reject };
}
beforeEach(() => {
  get.mockReset();
  localStorage.setItem("user", JSON.stringify({ id: 4101 }));
  sessionStorage.setItem("active-business-profile:4101", "4102");
});
afterEach(() => { cleanup(); vi.useRealTimers(); localStorage.clear(); sessionStorage.clear(); });

describe("Gmail authorization destination", () => {
  it("accepts the endpoint generated by the installed Google OAuth client", () => {
    expect(gmailAuthorizationUrl(authUrl)).toBe(authUrl);
  });
  it.each([
    "https://accounts.google.com.attacker.test/o/oauth2/v2/auth",
    "https://accounts.google.com@attacker.test/o/oauth2/v2/auth",
    "https://attacker@accounts.google.com/o/oauth2/v2/auth",
    "http://accounts.google.com/o/oauth2/v2/auth",
    "https://accounts.google.com:444/o/oauth2/v2/auth",
    "https://accounts.google.com/o/oauth2/auth",
    "https://accounts.google.com/o/oauth2/v2/auth#redirect",
    "javascript:alert(1)", "//accounts.google.com/o/oauth2/v2/auth", undefined,
  ])("rejects an unsafe or unexpected destination: %s", value => {
    expect(() => gmailAuthorizationUrl(value)).toThrow();
  });
  it("maps stable errors and never renders arbitrary provider text", () => {
    expect(gmailCallbackErrorMessage("access_denied")).toContain("cancelled");
    expect(gmailCallbackErrorMessage("missing_scopes")).toContain("permissions");
    expect(gmailCallbackErrorMessage("configuration_changed")).toContain("settings changed");
    expect(gmailCallbackErrorMessage("mailbox_already_connected")).toContain("review existing connections");
    for (const value of ["<img src=x onerror=alert(1)>", "private-provider-message", "__proto__", "constructor"]) {
      expect(gmailCallbackErrorMessage(value)).toBe("Gmail could not be connected. Choose Connect Gmail to try again.");
    }
  });
});

describe("Gmail authorization request lifecycle", () => {
  it("coalesces clicks and navigates once to the validated authorization URL", async () => {
    const pending = deferred<{ url: string }>();
    get.mockReturnValueOnce(pending.promise);
    const redirect = vi.fn(), onError = vi.fn();
    const { result } = renderHook(() => useGmailAuthorization(onError, redirect));
    let attempt!: Promise<void>;
    act(() => { attempt = result.current.connect(); expect(result.current.connect()).toBe(attempt); });
    expect(result.current.connecting).toBe(true);
    expect(get).toHaveBeenCalledOnce();
    await act(async () => { pending.resolve({ url: authUrl }); await attempt; });
    expect(redirect).toHaveBeenCalledExactlyOnceWith(authUrl);
    expect(onError).not.toHaveBeenCalled();
  });
  it("allows retry after a rejection without echoing provider details", async () => {
    get.mockRejectedValueOnce(new Error("private token response")).mockResolvedValueOnce({ authUrl });
    const redirect = vi.fn(), onError = vi.fn();
    const { result } = renderHook(() => useGmailAuthorization(onError, redirect));
    await act(async () => { await result.current.connect(); });
    expect(result.current.connecting).toBe(false);
    expect(onError.mock.calls[0][0]).not.toContain("private");
    await act(async () => { await result.current.connect(); });
    expect(redirect).toHaveBeenCalledExactlyOnceWith(authUrl);
  });
  it("rejects a malicious response and keeps retry available", async () => {
    get.mockResolvedValueOnce({ url: "https://attacker.test/", authUrl });
    const redirect = vi.fn(), onError = vi.fn();
    const { result } = renderHook(() => useGmailAuthorization(onError, redirect));
    await act(async () => { await result.current.connect(); });
    expect(redirect).not.toHaveBeenCalled();
    expect(onError).toHaveBeenCalledOnce();
    expect(result.current.connecting).toBe(false);
  });
  it.each(["business", "account", "unmount", "unauthorized"] as const)("ignores a late authorization response after %s changes", async change => {
    const pending = deferred<{ url: string }>();
    get.mockReturnValueOnce(pending.promise);
    const redirect = vi.fn(), onError = vi.fn();
    const { result, unmount } = renderHook(() => useGmailAuthorization(onError, redirect));
    let attempt!: Promise<void>;
    act(() => { attempt = result.current.connect(); });
    act(() => {
      if (change === "business") selectBusinessProfile(4103);
      else if (change === "account") localStorage.setItem("user", JSON.stringify({ id: 5101 }));
      else if (change === "unmount") unmount();
      else window.dispatchEvent(new Event("auth:unauthorized"));
    });
    await act(async () => { pending.resolve({ url: authUrl }); await attempt; });
    expect(redirect).not.toHaveBeenCalled();
    expect(onError).not.toHaveBeenCalled();
    if (change !== "unmount") expect(result.current.connecting).toBe(false);
  });
  it("rejects a changed business even before a remount or change event", async () => {
    const pending = deferred<{ url: string }>();
    get.mockReturnValueOnce(pending.promise);
    const redirect = vi.fn();
    const { result } = renderHook(() => useGmailAuthorization(vi.fn(), redirect));
    let attempt!: Promise<void>;
    act(() => { attempt = result.current.connect(); });
    sessionStorage.setItem("active-business-profile:4101", "4103");
    await act(async () => { pending.resolve({ url: authUrl }); await attempt; });
    expect(redirect).not.toHaveBeenCalled();
  });
  it("bounds a request that ignores abort and permits retry after timeout in StrictMode", async () => {
    vi.useFakeTimers();
    const pending = deferred<{ url: string }>();
    get.mockReturnValueOnce(pending.promise).mockResolvedValueOnce({ url: authUrl });
    const redirect = vi.fn(), onError = vi.fn();
    const { result } = renderHook(() => useGmailAuthorization(onError, redirect), { wrapper: StrictMode });
    let attempt!: Promise<void>;
    act(() => { attempt = result.current.connect(); });
    await act(async () => { await vi.advanceTimersByTimeAsync(GMAIL_AUTHORIZATION_TIMEOUT_MS); await attempt; });
    expect(result.current.connecting).toBe(false);
    expect(get.mock.calls[0][1]?.signal?.aborted).toBe(true);
    expect(onError).toHaveBeenCalledOnce();
    await act(async () => { await result.current.connect(); pending.resolve({ url: authUrl }); });
    expect(redirect).toHaveBeenCalledExactlyOnceWith(authUrl);
    expect(vi.getTimerCount()).toBe(0);
  });
});
