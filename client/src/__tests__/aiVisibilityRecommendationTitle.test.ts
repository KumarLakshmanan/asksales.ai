import { describe, expect, it } from 'vitest';
import { recommendationTitle } from '@/components/ai-visibility/workspace-ui';

describe('fix titles', () => {
  it('uses the readable rule label when the rule id is stored', () => {
    expect(
      recommendationTitle({ module: 'seo', title: 'headings · missing h1', evidence: { ruleId: 'headings.missing_h1' } }),
    ).toBe('Missing primary heading');
  });

  it('recovers the rule from titles generated by older analyses', () => {
    expect(recommendationTitle({ module: 'seo', title: 'headings · missing h1', evidence: {} })).toBe(
      'Missing primary heading',
    );
    expect(recommendationTitle({ module: 'seo', title: 'links · broken', evidence: null })).toBe('Broken links');
  });

  it('keeps written titles and non-SEO fixes as they are', () => {
    expect(recommendationTitle({ module: 'seo', title: 'Fix the pricing page', evidence: {} })).toBe(
      'Fix the pricing page',
    );
    expect(recommendationTitle({ module: 'aeo', title: 'faq · missing', evidence: {} })).toBe('faq · missing');
  });
});
